"""Write results/synthetic.md from results/synthetic.json (made by train.py)."""

from __future__ import annotations

import json

from simucore_ai import labels
from simucore_ai.features import describe
from simucore_ai.train import RESULTS


def f(x: object) -> str:
    return "–" if x is None else f"{x:.3f}" if isinstance(x, float) else str(x)


def markdown(r: dict) -> str:
    out = [
        "# Results on synthetic data", "",
        f"Trained {r['made_at']}. Generated by `simucore_ai/report.py`. Horizon "
        f"{r['targets']['horizon_s']} s, gap {r['targets']['gap_s']} s.", "",
        ("The test sets below consist of episodes generated for the first time after the models were "
         f"frozen (`final.py`, {r['tested_at']}). An earlier test set was looked at while features "
         "were designed; its numbers are kept in `synthetic.json` under `development_test`."
         if "tested_at" in r else "DEVELOPMENT numbers: run `simucore_ai/final.py`."), "",
        "## Sets (split by episode, never by row)", "",
        "| Set | Used for | Episodes | Rows | Positive (degradation) | Positive (failure) |",
        "|---|---|---|---|---|---|"]
    use = {"train": "learning", "valid": "when to stop boosting; anomaly threshold",
           "calib": "calibration of probabilities; warning threshold",
           "test": "the numbers below", "shifted": "the same, in another world"}
    for k, v in r["sets"].items():
        out.append(f"| {k} | {use[k]} | {v['episodes']} | {v['rows']} | "
                   f"{v['degradation']['positive']} of {v['degradation']['usable']} | "
                   f"{v['failure']['positive']} of {v['failure']['usable']} |")
    out += ["", "## Anomaly detection (Isolation Forest, unsupervised)", "",
            f"Share of abnormal moments in training, tried on the validation set (average precision): "
            f"{r['anomaly_training']['tried']}; chosen: {r['anomaly_training']['chosen']}.", "",
            "| Set | Precision | Recall | F1 | ROC-AUC | Average precision | False alarms per normal "
            "moment | ROC-AUC of 'largest deviation' | Condition named correctly |",
            "|---|---|---|---|---|---|---|---|---|"]
    for s in ("test", "shifted"):
        a = r[s]["anomaly"]
        x = a["isolation_forest"]
        out.append(f"| {s} | {f(x['precision'])} | {f(x['recall'])} | {f(x['f1'])} | "
                   f"{f(x['roc_auc'])} | {f(x['average_precision'])} | "
                   f"{f(x['false_positive_rate'])} | {f(a['baseline_largest_deviation']['roc_auc'])} | "
                   f"{f(a['condition_named_correctly'])} |")
    out += ["", "Disturbances in which an anomaly was confirmed (test set): " + ", ".join(
        f"{k} {v['noticed']}/{v['of']}" for k, v in r["test"]["anomaly"]["disturbances_noticed"].items())
        + ".", "", "## Failure prediction (XGBoost, supervised)", "",
        "| Set | Target | Precision | Recall | F1 | ROC-AUC | Average precision | Brier | "
        "Brier of the average | ROC-AUC logistic regression | ROC-AUC simple rule |",
        "|---|---|---|---|---|---|---|---|---|---|---|"]
    for s in ("test", "shifted"):
        for t in labels.TARGETS:
            x = r[s][t]["xgboost"]
            out.append(
                f"| {s} | {t} | {f(x['precision'])} | {f(x['recall'])} | {f(x['f1'])} | "
                f"{f(x['roc_auc'])} | {f(x['average_precision'])} | {f(x['brier'])} | "
                f"{f(x['brier_of_always_saying_the_average'])} | "
                f"{f(r[s][t]['baseline_logistic_regression']['roc_auc'])} | "
                f"{f(r[s][t]['baseline_rule']['roc_auc'])} |")
    out += ["", "As events: was the beginning announced, and how often was it a false alarm?", "",
            "| Set | Target | Announced | ≥ 10 s before | ≥ 30 s before | Median lead | Alarms | "
            "False alarms | per service-hour |", "|---|---|---|---|---|---|---|---|---|"]
    for s in ("test", "shifted"):
        for t in labels.TARGETS:
            e = r[s][t]["events"]
            out.append(f"| {s} | {t} | {e['announced']} of {e['failures']} | "
                       f"{e['announced_10s_before']} | {e['announced_30s_before']} | "
                       f"{f(e['lead_s_median'])} s | {e['alarms']} | {e['false_alarms']} | "
                       f"{f(e['false_alarms_per_service_hour'])} |")
    out += ["", "### By kind of trouble (test set, failure)", "", "| Kind | Announced |", "|---|---|"]
    for k, v in r["test"]["failure"]["events"]["by_kind"].items():
        out.append(f"| {k} | {v['announced']} of {v['of']} |")
    out += ["", "### Is a stated probability true? (test set)", "",
            "| Target | " + " | ".join(f"said {i / 10:.1f}–{(i + 1) / 10:.1f}" for i in range(10))
            + " |", "|---|" + "---|" * 10]
    for t in labels.TARGETS:
        cells = {int(min(9, b["said"] * 10)): b for b in r["test"][t]["reliability"]}
        out.append(f"| {t}: happened | " + " | ".join(
            f"{cells[i]['happened']:.2f}" if i in cells else "–" for i in range(10)) + " |")
    out += ["", "### Most important features (share of gain)", ""]
    for t in labels.TARGETS:
        top = list(r["importance"][t].items())[:8]
        out.append(f"* {t}: " + ", ".join(f"{describe(k)} {v:.0%}" for k, v in top))
    out += ["", "### Check for leakage", "",
            "Trained on shuffled labels, a model must know nothing (ROC-AUC 0.5). Five tries each:", ""]
    for t in labels.TARGETS:
        s = r["sanity"][t]
        sh = s["auc_after_shuffling_labels"]
        out.append(f"* {t}: {', '.join(f(x) for x in sh['each'])} (mean {f(sh['mean'])}); with the true "
                   f"labels {f(s['auc_with_true_labels'])}")
    return "\n".join(out) + "\n"


def main() -> None:
    r = json.loads((RESULTS / "synthetic.json").read_text(encoding="utf-8"))
    (RESULTS / "synthetic.md").write_text(markdown(r), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
